#!/usr/bin/env bash
set -euo pipefail

API_BASE="${API_BASE:-http://localhost:8080}"
RUNS="${RUNS:-3}"
QUERY_TEXT="${QUERY_TEXT:-slow search timeout}"

if ! command -v curl >/dev/null 2>&1; then
  echo "curl is required" >&2
  exit 1
fi

run_timed() {
  local name="$1"
  local method="$2"
  local url="$3"
  local data="${4:-}"

  local i
  for i in $(seq 1 "$RUNS"); do
    if [[ -n "$data" ]]; then
      curl -s -o /dev/null -w "${name},${i},%{http_code},%{time_total}\n" \
        -H "Content-Type: application/json" \
        -X "$method" \
        -d "$data" \
        "$url"
    else
      curl -s -o /dev/null -w "${name},${i},%{http_code},%{time_total}\n" \
        -X "$method" \
        "$url"
    fi
  done
}

echo "endpoint,run,status,time_seconds"

run_timed "health" "GET" "${API_BASE}/health"
run_timed "list" "GET" "${API_BASE}/defects/list?limit=10&offset=0"
run_timed "query" "POST" "${API_BASE}/defects/query" "{\"query\":\"${QUERY_TEXT}\",\"n_results\":3}"
run_timed "summary" "GET" "${API_BASE}/defects/summary"

# Ingest last to avoid altering query/summary behavior too early in the run.
run_timed "ingest" "POST" "${API_BASE}/defects/ingest" "{\"title\":\"benchmark defect\",\"description\":\"generated by migration benchmark\",\"project\":\"migration\",\"severity\":\"medium\",\"status\":\"open\"}"
